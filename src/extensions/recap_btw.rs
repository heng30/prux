//! `btw` 与 `recap` 两个扩展的模块根。
//!
//! `/btw` 只读旁问、`/recap` 一行会话小结（系统消息），共用同一套底座
//! （[`shared`]：转录摘录、折行、一次性模型请求）。`auto-title` 也复用这里的一次性
//! 请求（含 OAuth 刷新与思考模型的输出下限），所以 `shared` 对 crate 内可见。
//!
//! 为什么拆成两个扩展：两者虽然都只在用户**显式**发起时才有动作，但交互面完全不同——
//! 旁问要一个可连续追问的面板，小结只要往聊天区推一条系统消息；绑在一起只会让两边互相迁就。
//!
//! 两个扩展都**默认不启用**，且只在 `Dev` / `Creator` 扩展模式下可用。

pub(crate) mod shared;

pub mod btw;
pub mod recap;
