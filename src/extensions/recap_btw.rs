//! `btw` 与 `recap` 两个扩展的模块根。
//!
//! `/btw` 只读旁问、`/recap` 一行会话小结，共用同一套底座（[`shared`]：转录摘录、折行、一次性模型请求）。
//!
//! 为什么拆成两个扩展：`/btw` 只在用户**显式**发起时才有动作，而 `/recap` 开启后会在
//! **空闲时自动**发起模型请求——"要不要让它在后台花 token"这个开关不该和旁问绑在一起。
//!
//! 两个扩展都**默认不启用**，且只在 `Dev` / `Creator` 扩展模式下可用。

mod config;
mod shared;

pub mod btw;
pub mod recap;
